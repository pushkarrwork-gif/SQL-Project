S.FIRSTNAME,S.LASTNAME,C.COURSE_NAME 
FROM STUDENTS S 
JOIN 
ENROLLMENTS E 
ON S.STUDENT_ID=E.STUDENT_ID 
JOIN 
COURSES C 
ON E.COURSE_ID=C.COURSE_ID where E.COURSE_ID IN (SELECT
 COURSE_ID 
