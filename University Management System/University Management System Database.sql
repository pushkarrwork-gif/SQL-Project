create database UNIVERSITY_MANAGEMENT_SYSTEM;

USE UNIVERSITY_MANAGEMENT_SYSTEM;

CREATE TABLE STUDENTS
(STUDENT_ID int PRIMARY KEY,
FIRSTNAME VARCHAR(20),
LASTNAME VARCHAR(20),
 EMAIL VARCHAR (50),
 ENROLLMENT_DATE DATE);
 
DESC STUDENTS;
SELECT * FROM STUDENTS;

CREATE TABLE COURSES
(COURSE_ID varchar(10) PRIMARY KEY,
COURSE_NAME VARCHAR(50),
CREDITS INT);

DESC COURSES;
SELECT * FROM COURSES;

CREATE TABLE PROFESSORS
(PROFESSORS_ID varchar(10) PRIMARY KEY,
PROFESSOR_NAME VARCHAR (50),
DEPARTMENT VARCHAR(50));

DESC PROFESSORS;
select * FROM PROFESSORS;

CREATE TABLE ENROLLMENTS
(ENROLLMENT_ID INT PRIMARY KEY,
STUDENT_ID INT,
COURSE_ID varchar(10),
ENROLLMENT_DATE DATE,
GRADE VARCHAR(10),
constraint STUDENT_FK FOREIGN KEY (STUDENT_ID) references STUDENTS(STUDENT_ID),
 CONSTRAINT COURSE_FK FOREIGN KEY (COURSE_ID) references COURSES(COURSE_ID));
 
DESC ENROLLMENTS;
SELECT * FROM ENROLLMENTS;

CREATE TABLE DEPARTMENTS
(DEPARTMENT_ID varchar(10) PRIMARY KEY,
DEPARTMENT_NAME VARCHAR (50),
 BUILDING VARCHAR (20));
 
DESC DEPARTMENTS;
SELECT * FROM DEPARTMENTS;

CREATE TABLE PROFESSORS_DEPARTMENT
(PROFESSORS_ID varchar(10),
DEPARTMENT_ID varchar(10),
CONSTRAINT PROFESSORS_FK FOREIGN KEY (PROFESSORS_ID) references PROFESSORS(PROFESSORS_ID),
CONSTRAINT DEPARTMENT_FK FOREIGN KEY (DEPARTMENT_ID) references DEPARTMENTS(DEPARTMENT_ID));

DESC PROFESSORS_DEPARTMENT;
SELECT * FROM PROFESSORS_DEPARTMENT;




-- List the first and last name of all the students who enrolled in the year 2023.
SELECT
 FIRSTNAME, LASTNAME, YEAR(ENROLLMENT_DATE) AS ENROLLMENT_YEAR 
 FROM 
 STUDENTS
 WHERE YEAR(ENROLLMENT_DATE)=2023;

-- List the names of all courses that are worth exactly 4 credits.
SELECT 
COURSE_NAME, CREDITS 
FROM 
COURSES 
WHERE CREDITS=4;

-- Write a query to display the first and last names of all students along with the name of their major 
SELECT
 S.FIRSTNAME,S.LASTNAME,COURSE_NAME AS MAJOR 
 FROM 
 STUDENTS S 
 LEFT JOIN 
 ENROLLMENTS E
 ON S.STUDENT_ID=E.STUDENT_ID 
 INNER JOIN 
 COURSES C 
 ON E.COURSE_ID=C.COURSE_ID;

-- Find the total number of students enrolled in each CourseID
SELECT 
COURSE_ID,COUNT(STUDENT_ID) AS STUDENTS_ENROLLED 
FROM 
ENROLLMENTS 
GROUP BY COURSE_ID;

-- List the DepartmentName and the total count of professors working in each department.
 SELECT
 D.DEPARTMENT_NAME,COUNT(DISTINCT(P.PROFESSORS_ID)) AS PROFESSOR_COUNT 
 FROM
 DEPARTMENTS D 
 INNER JOIN 
 PROFESSORS_DEPARTMENT P 
 ON D.DEPARTMENT_ID=P.DEPARTMENT_ID 
 GROUP BY DEPARTMENT_NAME 
 ORDER BY PROFESSOR_COUNT; 

-- Find the first and last names of students who scored an A in the course "Digital Marketing". 
SELECT 
S.FIRSTNAME,S.LASTNAME,E.GRADE,C.COURSE_NAME 
FROM 
STUDENTS S 
JOIN 
ENROLLMENTS E 
ON S.STUDENT_ID=E.STUDENT_ID 
JOIN COURSES C ON E.COURSE_ID=C.COURSE_ID WHERE COURSE_NAME="Digital Marketing" AND GRADE="A" ;

-- Write a query to find out how many students enrolled in the university during each EnrollmentYear.
SELECT 
YEAR(ENROLLMENT_DATE) AS ENROLLMENT_YEAR,COUNT(*) AS NO_OF_STUDENTS 
FROM 
STUDENTS 
GROUP BY YEAR(ENROLLMENT_DATE) 
ORDER BY ENROLLMENT_YEAR;

-- Write a query to find all professors whose Department is 'Physics'.
SELECT 
P.PROFESSOR_NAME,DP.DEPARTMENT_ID,D.DEPARTMENT_NAME 
FROM 
PROFESSORS P
 JOIN 
 PROFESSORS_DEPARTMENT DP 
 ON P.PROFESSORS_ID=DP.PROFESSORS_ID 
 JOIN 
 DEPARTMENTS D 
 WHERE DEPARTMENT_NAME 
 LIKE "History";

-- Write a query to select CourseName and a new column CourseLevel from the Courses table. If Credits are greater than or equal to 4, set CourseLevel to 'Advanced', otherwise 'Basic'.
SELECT 
COURSE_NAME, 
CASE 
WHEN CREDITS=4 THEN "ADVANCE" 
WHEN CREDITS<=3 THEN "BASIC" 
END AS COURSE_LEVEL 
FROM COURSES ORDER BY COURSE_LEVEL;

-- Write a query to find all Students who are enrolled in a course that has more than 30 students. Use a subquery to find these CourseIDs.
SELECT
 COURSE_ID 
 FROM ENROLLMENTS 
 GROUP BY COURSE_ID 
 HAVING COUNT(STUDENT_ID)>=50;

