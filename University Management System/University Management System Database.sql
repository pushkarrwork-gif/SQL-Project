 HAVING COUNT(STUDENT_ID)>=50);

-- Write a query to select the top 3 COURSES with the most students enrolled in THEM.
SELECT 
C.COURSE_NAME,COUNT(S.STUDENT_ID) AS STUDENT_COUNT 
FROM 
COURSES C 
JOIN 
ENROLLMENTS E
 ON C.COURSE_ID=E.COURSE_ID 
 JOIN 
 STUDENTS S 
 ON E.STUDENT_ID=S.STUDENT_ID 
 GROUP BY COURSE_NAME 
 ORDER BY STUDENT_COUNT
 DESC LIMIT 3;

-- write a query to retrive StudentID and rank them based on grades.
SELECT 
STUDENT_ID,GRADE,RANK() 
OVER (ORDER BY GRADE) AS STUDENT_RANK 
FROM ENROLLMENTS ;

